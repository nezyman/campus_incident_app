import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'core/theme.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'providers/controllers.dart';
import 'providers/providers.dart';
import 'screens/auth/login_screen.dart';
import 'screens/home/home_shell.dart';
import 'screens/staff/staff_shell.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const ProviderScope(child: CampusReportsApp()));
}

class CampusReportsApp extends StatelessWidget {
  const CampusReportsApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Campus Reports',
      debugShowCheckedModeBanner: false,
      theme: buildTheme(),
      home: const AuthGate(),
    );
  }
}

/// Decides what to show: login, student home, or staff dashboard (role-based).
class AuthGate extends ConsumerWidget {
  const AuthGate({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final auth = ref.watch(authStateProvider);

    return auth.when(
      loading: () => const _Splash(),
      error: (e, _) => Scaffold(body: Center(child: Text('Error: $e'))),
      data: (firebaseUser) {
        if (firebaseUser == null) return const LoginScreen();

        final profile = ref.watch(currentUserProvider);
        return profile.when(
          loading: () => const _Splash(),
          error: (e, _) => Scaffold(body: Center(child: Text('Error: $e'))),
          data: (user) {
            if (user == null) {
              // Profile document is still being created (or is missing).
              return _Splash(
                  onSignOut: () =>
                      ref.read(authControllerProvider.notifier).logout());
            }
            return user.isStaff ? const StaffShell() : const HomeShell();
          },
        );
      },
    );
  }
}

class _Splash extends StatelessWidget {
  const _Splash({this.onSignOut});
  final VoidCallback? onSignOut;

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      body: Center(
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            const CircularProgressIndicator(),
            if (onSignOut != null) ...[
              const SizedBox(height: 24),
              TextButton(onPressed: onSignOut, child: const Text('Sign out')),
            ],
          ],
        ),
      ),
    );
  }
}
